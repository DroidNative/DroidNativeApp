package app.droidnative.display

import android.content.Context
import android.hardware.input.InputManager
import android.os.Build
import android.os.Handler
import android.os.Looper
import android.util.Log
import android.view.InputDevice
import android.view.KeyCharacterMap
import android.view.KeyEvent
import app.droidnative.env.EnvPaths
import app.droidnative.env.EnvService
import app.droidnative.env.Proot
import java.io.File
import java.util.Locale

/**
 * Keeps the Linux keyboard layout in step with the hardware keyboard Android
 * sees. Keys reach Linux by scancode (KeyMap.toEvdev); what each key types
 * comes from the keymap. Android has no public API for the name of the
 * chosen layout, so the keymap is generated from the keyboard's character
 * map: what every physical key types plain, with Shift, AltGr and both
 * (dead keys included), as an xkb layout "android" compiled in the guest.
 * Without a hardware keyboard the default (us) keymap stays.
 */
object HardwareKeyboard {
    private const val TAG = "dn-keyboard"

    /** Right Alt selects level 3 in the current keymap. */
    @Volatile var altGrIsLevel3 = false
        private set

    private var lastSymbols: String? = null
    private val main = Handler(Looper.getMainLooper())

    /** Follows keyboards being connected and disconnected. */
    fun watch(context: Context) {
        val app = context.applicationContext
        val im = app.getSystemService(InputManager::class.java) ?: return
        im.registerInputDeviceListener(object : InputManager.InputDeviceListener {
            override fun onInputDeviceAdded(id: Int) = schedule(app)
            override fun onInputDeviceRemoved(id: Int) = schedule(app)
            override fun onInputDeviceChanged(id: Int) = schedule(app)
        }, main)
        schedule(app)
    }

    private fun schedule(context: Context) {
        // Devices come and go in bursts (a keyboard is several input devices)
        main.removeCallbacksAndMessages(TAG)
        main.postAtTime({ Thread({ refresh(context) }, "dn-keymap").start() }, TAG,
            android.os.SystemClock.uptimeMillis() + 1000)
    }

    @Synchronized
    fun refresh(context: Context) {
        val paths = EnvPaths(context)
        val device = physicalKeyboard()
        val symbols = device?.let { symbols(it) }
        if (symbols == lastSymbols) return
        lastSymbols = symbols
        if (symbols == null) {
            altGrIsLevel3 = false
            if (paths.keymap.isFile) EnvService.compositor.setKeymap(paths.keymap.path)
            Log.i(TAG, "no hardware keyboard: default keymap")
            return
        }
        val dir = File(paths.runDir, "xkb/symbols")
        dir.mkdirs()
        File(dir, "android").writeText(symbols)
        val out = File(paths.runDir, "keymap-hw.xkb")
        val r = Proot(paths).sh(
            "xkbcli compile-keymap --include ${EnvPaths.GUEST_RUN_DIR}/xkb --include-defaults " +
                "--layout android > ${EnvPaths.GUEST_RUN_DIR}/keymap-hw.xkb.tmp && " +
                "mv ${EnvPaths.GUEST_RUN_DIR}/keymap-hw.xkb.tmp ${EnvPaths.GUEST_RUN_DIR}/keymap-hw.xkb",
            timeoutMs = 30_000)
        if (!r.ok || !out.isFile) {
            Log.w(TAG, "keymap compilation failed: ${r.output.take(400)}")
            lastSymbols = null
            return
        }
        altGrIsLevel3 = symbols.contains("ralt_switch")
        EnvService.compositor.setKeymap(out.path)
        Log.i(TAG, "keymap from ${device.name} applied")
    }

    private fun physicalKeyboard(): InputDevice? =
        InputDevice.getDeviceIds().asSequence().mapNotNull { InputDevice.getDevice(it) }.firstOrNull {
            !it.isVirtual && it.keyboardType == InputDevice.KEYBOARD_TYPE_ALPHABETIC &&
                it.supportsSource(InputDevice.SOURCE_KEYBOARD)
        }

    /** xkb symbols file "android" with the device's characters, or null. */
    fun symbols(device: InputDevice): String {
        val kcm = device.keyCharacterMap
        val lines = ArrayList<String>()
        var level3 = false
        for ((evdev, xkbName) in KEYS) {
            val location = KeyMap.locationOf(evdev)
            if (location == 0) continue
            // API 33+: the key code the layout gives this physical key
            val keyCode = if (Build.VERSION.SDK_INT >= 33) device.getKeyCodeForKeyLocation(location) else location
            val syms = LEVELS.map { meta -> keysym(kcm.get(keyCode, meta)) }
            if (syms.all { it == "NoSymbol" }) continue
            val used = if (syms[2] == "NoSymbol" && syms[3] == "NoSymbol") syms.take(2) else syms.also { level3 = true }
            lines += "    key <$xkbName> { [ ${used.joinToString(", ")} ] };"
        }
        return buildString {
            append("// Generated by DroidNative from the Android keyboard layout\n")
            append("default partial alphanumeric_keys\n")
            append("xkb_symbols \"basic\" {\n")
            append("    include \"us(basic)\"\n")
            append("    name[Group1] = \"Android\";\n")
            lines.forEach { append(it).append('\n') }
            if (level3) append("    include \"level3(ralt_switch)\"\n")
            append("};\n")
        }
    }

    private val LEVELS = intArrayOf(
        0,
        KeyEvent.META_SHIFT_ON or KeyEvent.META_SHIFT_LEFT_ON,
        KeyEvent.META_ALT_ON or KeyEvent.META_ALT_RIGHT_ON,
        KeyEvent.META_ALT_ON or KeyEvent.META_ALT_RIGHT_ON or KeyEvent.META_SHIFT_ON or KeyEvent.META_SHIFT_LEFT_ON,
    )

    private fun keysym(value: Int): String {
        if (value == 0) return "NoSymbol"
        if (value and KeyCharacterMap.COMBINING_ACCENT != 0)
            return DEAD[value and KeyCharacterMap.COMBINING_ACCENT_MASK] ?: "NoSymbol"
        if (value < 0x20 || value == 0x7f) return "NoSymbol"
        return String.format(Locale.ROOT, "U%04X", value)
    }

    // Combining accents (dead keys) -> xkb dead keysyms
    private val DEAD = mapOf(
        0x0300 to "dead_grave", 0x0301 to "dead_acute", 0x0302 to "dead_circumflex",
        0x0303 to "dead_tilde", 0x0308 to "dead_diaeresis", 0x030A to "dead_abovering",
        0x0327 to "dead_cedilla", 0x030C to "dead_caron", 0x0304 to "dead_macron",
        0x0306 to "dead_breve", 0x0307 to "dead_abovedot", 0x030B to "dead_doubleacute",
        0x0328 to "dead_ogonek",
    )

    // Typing keys: evdev code -> xkb key name
    private val KEYS: List<Pair<Int, String>> = buildList {
        for (i in 0 until 12) add((2 + i) to "AE%02d".format(Locale.ROOT, i + 1))   // 1..0 - =
        for (i in 0 until 12) add((16 + i) to "AD%02d".format(Locale.ROOT, i + 1))  // q..p [ ]
        for (i in 0 until 11) add((30 + i) to "AC%02d".format(Locale.ROOT, i + 1))  // a..l ; '
        add(41 to "TLDE")
        add(43 to "BKSL")
        for (i in 0 until 10) add((44 + i) to "AB%02d".format(Locale.ROOT, i + 1))  // z..m , . /
        add(86 to "LSGT")
    }
}
